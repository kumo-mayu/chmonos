namespace BoothAssetManager.App.ViewModels;

/// <summary>
/// 裏の取得（取り込みの④⑤・使っていない間の取得・期限の取り直し）が商品の画像を置いたことを受ける画面。
///
/// 知らせは主画面が1か所で受けて今の画面へ配る。前は検索と商品ページ（単独・編集画面の中）にしか配っておらず、
/// フォルダビュー・改変の画面に組み込んだ商品ページや、ショップ・フォルダのカードは、取得の最中に開くと
/// 「画像を取得中」のまま残っていた（2026-09-29 の洗い出し 6）。
/// 画面の側に受け口を置けば、主画面は画面の種類を並べずに済み、画面を足したときもその画面の中で完結する
/// </summary>
internal interface IItemImagesListener
{
    /// <summary>この商品の画像が置かれた（UIスレッドで呼ばれる）。持っている商品ページ・カードの絵を引き直す。</summary>
    void NoteItemImagesSaved(string itemId);
}
