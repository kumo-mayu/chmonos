namespace BoothAssetManager.App.ViewModels;

/// <summary>
/// 画面を離れたときの一覧の位置。**先頭に見えていた項目と、その項目の上端が一覧の上端から何 px ずれていたか**で覚える
/// （ユーザ判断 2026-09-28：ショップの一覧とショップの中は、戻ったら前の位置に戻す）。
/// </summary>
/// <remarks>
/// スクロールの量（px）で覚えない理由：カードの一覧は幅から列数を決めて行に切るので、開き直した直後は1列で組まれ、
/// 幅が決まってから組み直る。窓の幅が変わっていれば行の数も変わる。戻るまでの間に商品を外したり、
/// 登録を外したりすると、上の行がずれる。量で戻すと、そのどれでも別の所に着く。
/// 項目で覚えれば、列数や件数が変わっても同じ物が先頭に来る。見つからなければ（消えた・絞りで外れた）先頭から出す。
/// </remarks>
/// <param name="Key">先頭に見えていた項目の鍵（ショップはサブドメイン、商品は ID）。行に切った一覧では行の先頭のカード。</param>
/// <param name="Offset">その項目の上端の、一覧の見える範囲の上端からの位置（px。上へはみ出していれば負）。</param>
public sealed record ListAnchor(string Key, double Offset);
